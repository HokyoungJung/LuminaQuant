    out: dict[str, dict[str, Any]] = {}
    for row in rows:
        split = str(row.get("split") or "")
        if split not in SPLIT_ORDER:
            continue
        out[split] = {
            "total_return": _safe_float(row.get("total_return")),
            "max_drawdown": _safe_float(row.get("max_drawdown")),
            "sharpe": _safe_float(row.get("sharpe")),
            "sortino": _safe_float(row.get("sortino")),
            "smart_sortino": _safe_float(row.get("smart_sortino")),
            "calmar": _safe_float(row.get("calmar")),
            "return_mdd": _safe_float(row.get("return_mdd")),
            "trade_count": _safe_int(row.get("trade_event_count")),
            "active_return_hours": _safe_int(row.get("active_return_hours")),
            "liquidation_count": _safe_int(row.get("liquidation_count")),
            "account_wipeout_count": _safe_int(row.get("account_wipeout_count")),
            "minimum_margin_buffer": (
                None
                if row.get("minimum_margin_buffer") in {"", None}
                else _safe_float(row.get("minimum_margin_buffer"), -1.0)
            ),
        }
    return out


