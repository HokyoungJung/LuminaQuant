def _promotion_gate_reasons(
    split_metrics: Mapping[str, Mapping[str, Any]],
    *,
    cost_bps: float,
    candidate_universe_uses_locked_oos_bucket: bool = False,
    regenerated_train_validation_only: bool = True,
    promotability_scope: str = "live_candidate",
    strict_zero_liquidation: bool = True,
) -> list[str]:
    reasons: list[str] = []
    if not math.isclose(float(cost_bps), PRIMARY_COST_BPS, abs_tol=1e-9):
        reasons.append("primary_cost_not_10bps")
    missing = [split for split in SPLIT_ORDER if split not in split_metrics]
    if missing:
        reasons.append("missing_split_metrics:" + ",".join(missing))

    if candidate_universe_uses_locked_oos_bucket:
        reasons.append("candidate_universe_uses_locked_oos_bucket")
    if promotability_scope == "shadow_only":
        reasons.append("shadow_only_historical_oos_bucket_lineage")

    train = dict(split_metrics.get("train") or {})
    validation = dict(split_metrics.get("validation") or {})
    locked_oos = dict(split_metrics.get("locked_oos") or {})
    for split_name, metrics in (("validation", validation), ("locked_oos", locked_oos)):
        if _safe_float(metrics.get("total_return")) <= 0.0:
            reasons.append(f"{split_name}_return_non_positive")
        for metric_key in POSITIVE_PROMOTION_METRIC_KEYS:
            if _safe_float(metrics.get(metric_key)) <= 0.0:
                reasons.append(f"{split_name}_{metric_key}_non_positive")

    if _safe_float(train.get("total_return")) <= 0.0:
        reasons.append("train_return_non_positive")
    for metric_key in PROMOTION_METRIC_KEYS:
        train_value = _safe_float(train.get(metric_key))
        validation_value = _safe_float(validation.get(metric_key))
        locked_value = _safe_float(locked_oos.get(metric_key))
        if train_value <= validation_value:
            reasons.append(f"train_{metric_key}_not_above_validation")
        if train_value <= locked_value:
            reasons.append(f"train_{metric_key}_not_above_locked_oos")

    if _safe_float(locked_oos.get("max_drawdown"), 1.0) > high.OOS_MDD_BUDGET:
        reasons.append("locked_oos_mdd_above_25pct")

    total_liquidations = 0
    for split in SPLIT_ORDER:
        metrics = dict(split_metrics.get(split) or {})
        if _safe_int(metrics.get("account_wipeout_count")) > 0:
            reasons.append(f"{split}_account_wipeout_count_positive")
        total_liquidations += _safe_int(metrics.get("liquidation_count"))
        if metrics.get("minimum_margin_buffer") is not None and _safe_float(
            metrics.get("minimum_margin_buffer"), -1.0
        ) <= 0.0:
            reasons.append(f"{split}_minimum_margin_buffer_non_positive")
    if strict_zero_liquidation and total_liquidations > 0:
        reasons.append("liquidation_count_positive")

    return sorted(set(reasons))


def _promotion_gate_result(
    split_metrics: Mapping[str, Mapping[str, Any]],
    *,
    cost_bps: float,
    candidate_universe_uses_locked_oos_bucket: bool = False,
    regenerated_train_validation_only: bool = True,
    promotability_scope: str = "live_candidate",
    strict_zero_liquidation: bool = True,
) -> dict[str, Any]:
    reasons = _promotion_gate_reasons(
        split_metrics,
        cost_bps=float(cost_bps),
        candidate_universe_uses_locked_oos_bucket=bool(candidate_universe_uses_locked_oos_bucket),
        regenerated_train_validation_only=bool(regenerated_train_validation_only),
        promotability_scope=str(promotability_scope),
        strict_zero_liquidation=bool(strict_zero_liquidation),
    )
    return {
        "round_trip_slippage_fee_bps": float(cost_bps),
        "live_promotable_10bps": not reasons,
        "primary_10bps_promotion_gate_pass": not reasons,
        "primary_10bps_promotion_gate_reasons": reasons,
        "candidate_universe_uses_locked_oos_bucket": bool(candidate_universe_uses_locked_oos_bucket),
        "regenerated_train_validation_only": bool(regenerated_train_validation_only),
        "promotability_scope": str(promotability_scope),
        "strict_zero_liquidation": bool(strict_zero_liquidation),
    }


def promotion_gate(row: Mapping[str, Any]) -> dict[str, Any]:
    """Compatibility wrapper for tests and ad-hoc gate probes over flat rows."""
    split_metrics = _split_metrics_from_prefixed_row(row)
    result = _promotion_gate_result(
        split_metrics,
        cost_bps=_safe_float(row.get("round_trip_slippage_fee_bps"), PRIMARY_COST_BPS),
        candidate_universe_uses_locked_oos_bucket=_as_bool(
            row.get("candidate_universe_uses_locked_oos_bucket")
        ),
        regenerated_train_validation_only=_as_bool(row.get("regenerated_train_validation_only")),
        promotability_scope="shadow_only"
        if _as_bool(row.get("shadow_only"))
        else str(row.get("promotability_scope") or "live_candidate"),
        strict_zero_liquidation=True,
    )
    raw_params = row.get("params", row.get("params_json", {}))
    if isinstance(raw_params, Mapping):
        params = dict(raw_params)
    elif isinstance(raw_params, str) and raw_params.strip():
        try:
            loaded_params = json.loads(raw_params)
        except json.JSONDecodeError:
            loaded_params = {}
        params = dict(loaded_params) if isinstance(loaded_params, Mapping) else {}
    else:
        params = {}
    reasons = list(result["primary_10bps_promotion_gate_reasons"])
    if _as_bool(row.get("calendar_primary")) or _variant_has_calendar_rule(params):
        reasons.append("calendar_or_date_rule_forbidden")
    compatibility_reason_names = {
        "train_total_return_not_above_validation": "train_return_not_above_validation",
        "train_total_return_not_above_locked_oos": "train_return_not_above_locked_oos",
    }
    reasons = [compatibility_reason_names.get(reason, reason) for reason in reasons]
    reasons = sorted(set(reasons))
    return {
        "promotion_gate_pass": not reasons,
        "promotion_gate_reasons": reasons,
    }


