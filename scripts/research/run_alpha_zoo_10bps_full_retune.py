def _train_validation_score(split_metrics: Mapping[str, Mapping[str, Any]]) -> float:
    """Score only train+validation metrics; locked-OOS is intentionally unread."""
    train = dict(split_metrics.get("train") or {})
    validation = dict(split_metrics.get("validation") or {})
    val_return = _safe_float(validation.get("total_return"))
    train_return = _safe_float(train.get("total_return"))
    val_mdd = _safe_float(validation.get("max_drawdown"), 1.0)
    train_mdd = _safe_float(train.get("max_drawdown"), 1.0)
    score = (
        10.0 * val_return
        + 0.25 * train_return
        + 0.10 * _safe_float(validation.get("sharpe"))
        + 0.10 * _safe_float(validation.get("sortino"))
        + 0.10 * _safe_float(validation.get("smart_sortino"))
        + 0.10 * _safe_float(validation.get("calmar"))
        - 3.0 * max(0.0, val_mdd - high.OOS_MDD_BUDGET)
        - 0.25 * max(0.0, train_mdd - high.OOS_MDD_BUDGET)
    )
    if val_return <= 0.0:
        score -= 100.0 + abs(val_return) * 10.0
    if train_return <= 0.0:
        score -= 50.0 + abs(train_return) * 5.0
    return float(score)


