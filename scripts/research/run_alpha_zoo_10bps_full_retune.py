def _calendar_rule_reasons(params: Mapping[str, Any]) -> list[str]:
    reasons: list[str] = []
    for key, value in params.items():
        key_text = str(key)
        if isinstance(value, Mapping):
            nested = _calendar_rule_reasons(value)
            reasons.extend(f"{key_text}.{item}" for item in nested)
            continue
        is_calendar_key = key_text in CALENDAR_PARAM_KEYS
        if not is_calendar_key:
            continue
        if value not in (None, "", (), [], {}):
            reasons.append(key_text)
    return sorted(set(reasons))


def _variant_has_calendar_rule(params: Mapping[str, Any]) -> bool:
    return bool(_calendar_rule_reasons(params))


