def _scaled_param_variant(
    params: Mapping[str, Any],
    *,
    key: str,
    factor: float,
    suffix: str,
) -> tuple[str, dict[str, Any]] | None:
    if key not in params:
        return None
    value = _safe_float(params.get(key), math.nan)
    if not math.isfinite(value):
        return None
    out = dict(params)
    out[key] = value * factor
    return suffix, out


def _build_variant_inventory(source_live_payload: Mapping[str, Any]) -> list[dict[str, Any]]:
    selection = dict(source_live_payload.get("selection") or {})
    summaries = list(selection.get("strategy_summaries") or [])
    rows: list[dict[str, Any]] = []
    seen: set[tuple[str, str]] = set()
    for item in summaries:
        candidate_name = str(dict(item).get("candidate_name") or "")
        source = str(dict(item).get("candidate_source") or "source_live_aligned")
        params = dict(dict(item).get("params") or {})
        if not candidate_name:
            continue
        variants: list[tuple[str, dict[str, Any]]] = [("base", params)]
        for spec in (
            _scaled_param_variant(params, key="entry_threshold", factor=1.10, suffix="entry_10pct_stricter"),
            _scaled_param_variant(params, key="entry_threshold", factor=1.25, suffix="entry_25pct_stricter"),
            _scaled_param_variant(params, key="exit_threshold", factor=1.25, suffix="exit_hysteresis_25pct_wider"),
            _scaled_param_variant(params, key="max_hold_bars", factor=1.50, suffix="max_hold_50pct_longer"),
        ):
            if spec is not None:
                variants.append(spec)
        for variant_name, variant_params in variants:
            key = (candidate_name, variant_name)
            if key in seen:
                continue
            seen.add(key)
            rows.append(
                _variant_row(
                    candidate_name=candidate_name,
                    variant_name=variant_name,
                    params=variant_params,
                    source=source,
                )
            )
    return rows


