def _group_metric_rows_by_model(rows: Sequence[Mapping[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    grouped: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        if not math.isclose(_safe_float(row.get("round_trip_slippage_fee_bps")), PRIMARY_COST_BPS):
            continue
        model_id = str(row.get("model_id") or "")
        if not model_id:
            continue
        grouped.setdefault(model_id, []).append(dict(row))
    for model_id, model_rows in grouped.items():
        splits = {str(row.get("split")) for row in model_rows}
        missing = set(SPLIT_ORDER) - splits
        if missing:
            raise ValueError(f"{model_id} missing primary 10bps split rows: {sorted(missing)}")
    return grouped


