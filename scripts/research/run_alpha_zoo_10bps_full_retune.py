def _slug(value: Any) -> str:
    text = str(value or "").strip().lower()
    out = []
    for ch in text:
        if ch.isalnum():
            out.append(ch)
        elif ch == ".":
            out.append("p")
        else:
            out.append("_")
    return "_".join("".join(out).split("_")).strip("_") or "model"


