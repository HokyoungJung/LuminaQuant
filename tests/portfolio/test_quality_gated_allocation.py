"""Tests for the offline quality-gated sleeve allocator (Lane M2).

Covers: (a) happy-path round-trip through the REAL
``ArtifactPortfolioModeStrategy`` consumer (the emitted manifest does NOT
fail-close); (b) fail-closed path parametrized over the consumer's enumerated
reason codes; (c) allocation math (quality gate, ERC weight sum/cap,
determinism, graceful None/empty handling); (d) byte-golden manifest
serialization.

All synthetic return streams are generated by a deterministic linear
congruential generator (no numpy RNG, no scipy) so every test is bit-for-bit
reproducible. ASCII only.
"""

