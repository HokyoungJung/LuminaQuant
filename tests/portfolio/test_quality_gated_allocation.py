@pytest.mark.parametrize("case_name", sorted(_FAIL_CLOSED_CASES))
def test_induced_omission_fails_closed_to_cash(tmp_path: Path, case_name: str) -> None:
    manifest = _single_sleeve_manifest(tmp_path)
    mutate_fn, expected_reason = _FAIL_CLOSED_CASES[case_name]
    mutated = _mutate(manifest, mutate_fn)
    manifest_path = _write_manifest(tmp_path, mutated, case_name)

    definition = ARTIFACT_PORTFOLIO_MODE.resolve_portfolio_mode_definition(
        f"manifest:{manifest_path}"
    )

    assert definition.components == ()
    assert definition.cash_weight == 1.0
    assert definition.source_artifacts["manifest_fail_closed_to_cash"] == "true"
    assert definition.source_artifacts["manifest_fail_closed_reason"] == expected_reason


def test_missing_manifest_file_fails_closed_to_cash(tmp_path: Path) -> None:
    missing_path = tmp_path / "does-not-exist.json"

