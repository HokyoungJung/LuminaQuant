ARTIFACT_PORTFOLIO_MODE = importlib.util.module_from_spec(_SPEC)
assert _SPEC is not None and _SPEC.loader is not None
sys.modules[_SPEC.name] = ARTIFACT_PORTFOLIO_MODE
_SPEC.loader.exec_module(ARTIFACT_PORTFOLIO_MODE)


def _lcg_stream(seed: int, n: int) -> list[float]:
    """Deterministic linear-congruential PRNG stream in [0, 1) (Numerical Recipes constants)."""
    x = seed
    values: list[float] = []
    for _ in range(n):
        x = (1664525 * x + 1013904223) % (2**32)
        values.append(x / (2**32))
    return values


def _synthetic_returns(seed: int, n: int, *, drift: float, scale: float) -> list[float]:
    return [(value - 0.5) * scale + drift for value in _lcg_stream(seed, n)]


def _sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _single_sleeve_manifest(tmp_path: Path) -> dict[str, Any]:
    """A single strongly-positive-edge sleeve; the manifest must NOT fail-close."""
    source_path = tmp_path / "source.json"
    source_path.write_text(json.dumps({"ready": True}), encoding="utf-8")
    sleeves = {
        "sleeve_a": {
            "returns": _synthetic_returns(42, 64, drift=0.004, scale=0.01),
            "turnover": 0.0,
            "strategy_class": "MovingAverageCrossStrategy",
            "symbols": ["BTC/USDT"],
            "params": {"short_window": 4, "long_window": 12},
            "source_artifact_id": "src",
        }
    }
    source_artifacts = [
        {
            "id": "src",
            "path": str(source_path),
            "sha256": _sha256_of(source_path),
            "max_age_hours": 876_000,
            "ready": True,
            "portfolio_ready": True,
        }
    ]
    return build_allocation_manifest(sleeves, source_artifacts=source_artifacts, gross_cap=1.0)


def _write_manifest(tmp_path: Path, manifest: dict[str, Any], name: str) -> Path:
    path = tmp_path / f"{name}.json"
    path.write_text(json.dumps(manifest), encoding="utf-8")
    return path


# ---------------------------------------------------------------------------
# (a) Happy path: round-trip through the REAL consumer.
# ---------------------------------------------------------------------------


def test_manifest_round_trips_through_real_consumer_without_fail_closing(tmp_path: Path) -> None:
    manifest = _single_sleeve_manifest(tmp_path)
    manifest_path = _write_manifest(tmp_path, manifest, "manifest")

    definition = ARTIFACT_PORTFOLIO_MODE.resolve_portfolio_mode_definition(
        f"manifest:{manifest_path}"
    )

    assert "manifest_fail_closed_to_cash" not in definition.source_artifacts
    assert definition.cash_weight == 0.0
    assert [(c.component_id, c.weight, c.strategy_class) for c in definition.components] == [
        ("sleeve_a", 1.0, "MovingAverageCrossStrategy")
    ]


def test_manifest_constructs_the_real_strategy_and_stays_off_cash(tmp_path: Path) -> None:
    manifest = _single_sleeve_manifest(tmp_path)
    manifest_path = _write_manifest(tmp_path, manifest, "manifest")

    strategy = ARTIFACT_PORTFOLIO_MODE.ArtifactPortfolioModeStrategy(
        bars=SimpleNamespace(
            symbol_list=["BTC/USDT"], get_latest_bar_value=lambda *args, **kwargs: 100.0
        ),
        events=SimpleNamespace(put=lambda item: None),
        portfolio_mode=f"manifest:{manifest_path}",
    )

    assert strategy.definition.cash_weight != 1.0
    assert "manifest_fail_closed_to_cash" not in strategy.definition.source_artifacts
    assert [c.component_id for c in strategy.definition.components] == ["sleeve_a"]
    assert strategy.definition.components[0].weight == 1.0


