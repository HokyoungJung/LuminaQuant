_GOLDEN_MANIFEST_SHA256 = "b50db777149a7c4a5c3bba53f698ac330a8ce1998ab20674f04f69a59d2739b9"


def test_manifest_serialization_matches_pinned_byte_golden() -> None:
    sleeves = {
        "alpha": {
            "returns": _synthetic_returns(12345, 64, drift=0.0025, scale=0.01),
            "turnover": 0.01,
            "strategy_class": "MovingAverageCrossStrategy",
            "symbols": ["BTC/USDT"],
            "params": {"short_window": 4, "long_window": 12},
            "source_artifact_id": "golden_source",
        },
        "beta": {
            "returns": _synthetic_returns(67890, 64, drift=0.0018, scale=0.02),
            "turnover": 0.02,
            "strategy_class": "MovingAverageCrossStrategy",
            "symbols": ["ETH/USDT"],
            "params": {"short_window": 6, "long_window": 20},
            "source_artifact_id": "golden_source",
        },
    }
    source_artifacts = [
        {
            "id": "golden_source",
            "path": "var/reports/golden/source.json",
            "sha256": "a" * 64,
            "max_age_hours": 100_000,
            "ready": True,
            "portfolio_ready": True,
        }
    ]

    manifest = build_allocation_manifest(
        sleeves, source_artifacts=source_artifacts, method="erc", gross_cap=1.0
    )
    serialized = json.dumps(manifest, sort_keys=True)

    assert all(
        child["lagged_completed_shadow_optimizer_provenance"] is False
        for child in manifest["children"]
    )
    assert hashlib.sha256(serialized.encode("utf-8")).hexdigest() == _GOLDEN_MANIFEST_SHA256
